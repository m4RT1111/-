money_capital = 20000  # Подушка безопасности
salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
increase = 0.05  # Ежемесячный рост цен

months = 0  # Счетчик месяцев

while money_capital >= 0:
    # Текущий бюджет на месяц = подушка безопасности + зарплата
    current_budget = money_capital + salary

    # Проверяем, можем ли покрыть расходы
    if current_budget >= spend:
        # Уменьшаем подушку безопасности на разницу между тратами и зарплатой
        money_capital -= (spend - salary)

        # Увеличиваем траты на следующий месяц
        spend *= (1 + increase)

        # Увеличиваем количество месяцев
        months += 1
    else:
        break

print("Количество месяцев, которое можно протянуть без долгов:", months)
