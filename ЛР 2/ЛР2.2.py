salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
months = 10  # Количество месяцев, которое планируется протянуть без долгов
increase = 0.03  # Ежемесячный рост цен

money_capital = 0  # Начальное значение подушки безопасности

# Рассчитываем необходимую подушку
for month in range(months):
    # Определяем нехватку средств для покрытия текущих трат
    shortage = spend - salary

    # Если расходы больше зарплаты, добавляем нехватку в подушку безопасности
    if shortage > 0:
        money_capital += shortage

    # Увеличиваем траты на следующий месяц
    spend *= (1 + increase)

# Округляем результат до целого числа
money_capital = round(money_capital)

print(f"Подушка безопасности, чтобы протянуть {months} месяцев без долгов:", money_capital)
